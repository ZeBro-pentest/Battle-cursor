export function AgreementEffect({ onComplete }: { onComplete: () => void }) {
  const [canAccept, setCanAccept] = useState(false);
  const scrollRef = useRef<HTMLDivElement>(null);

  const handleScroll = () => {
    const el = scrollRef.current;
    if (!el) return;
    if (el.scrollTop + el.clientHeight >= el.scrollHeight - 10) {
      setCanAccept(true);
    }
  };

  return (
    <div className="effect-epic-overlay">
      <div className="effect-epic-box effect-agreement-box">
        <p className="effect-epic-title">Пользовательское соглашение</p>
        <div ref={scrollRef} className="effect-agreement-text" onScroll={handleScroll}>
          {TEXT}
        </div>
        {!canAccept && (
          <p className="effect-epic-hint-text">Прокрути до конца чтобы принять</p>
        )}
        <button className="effect-epic-btn" onClick={onComplete} disabled={!canAccept}>
          Принять
        </button>
      </div>
    </div>
  );
}
